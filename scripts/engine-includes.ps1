# Generates the pieces of scripts/installer.iss that depend on the engine
# payload actually present at build time (OCR languages are discovered from
# tesseract\tessdata, not assumed). Called by build.ps1 -Mode Installer.

[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$EngineRoot,
    [Parameter(Mandatory)][string]$OutDir
)

$root = (Resolve-Path -LiteralPath $EngineRoot).Path
$required = @(
    'ffmpeg\bin\ffmpeg.exe',
    'pandoc\pandoc.exe',
    'tesseract\tesseract.exe'
)
foreach ($relative in $required) {
    if (-not (Test-Path -LiteralPath (Join-Path $root $relative) -PathType Leaf)) {
        throw "Engine payload is missing '$relative' under $root"
    }
}

New-Item -ItemType Directory -Force -Path $OutDir | Out-Null

$friendly = @{
    eng = 'English'; deu = 'German'; ger = 'German'; fra = 'French'; fre = 'French'
    spa = 'Spanish'; ita = 'Italian'; por = 'Portuguese'; nld = 'Dutch'; dut = 'Dutch'
    pol = 'Polish'; rus = 'Russian'; jpn = 'Japanese'; kor = 'Korean'
    chi_sim = 'Chinese (Simplified)'; chi_tra = 'Chinese (Traditional)'
    ara = 'Arabic'; hin = 'Hindi'; tur = 'Turkish'; ukr = 'Ukrainian'
}

$tessdata = Join-Path $root 'tesseract\tessdata'
$languages = @()
if (Test-Path -LiteralPath $tessdata -PathType Container) {
    $languages = @(Get-ChildItem -LiteralPath $tessdata -Filter '*.traineddata' -File |
        ForEach-Object { $_.BaseName } |
        Sort-Object)
}
# English is the default when it ships; the rest stay opt-in.
$languages = @($languages | Where-Object { $_ -eq 'eng' }) + @($languages | Where-Object { $_ -ne 'eng' })

$components = New-Object System.Collections.Generic.List[string]
$files = New-Object System.Collections.Generic.List[string]
$fresh = New-Object System.Collections.Generic.List[string]
$registry = New-Object System.Collections.Generic.List[string]
$record = New-Object System.Collections.Generic.List[string]
$remove = New-Object System.Collections.Generic.List[string]

foreach ($code in $languages) {
    $id = 'lang_' + ($code.ToLowerInvariant() -replace '[^a-z0-9_]', '_')
    $label = if ($friendly.ContainsKey($code.ToLowerInvariant())) {
        $friendly[$code.ToLowerInvariant()]
    } else {
        $code
    }
    $components.Add("Name: ""tesseract\$id""; Description: ""OCR language: $label""; Types: full")
    $files.Add("Source: ""{#EngineRoot}\tesseract\tessdata\$code.traineddata""; DestDir: ""{app}\engines\tesseract\tessdata""; Components: tesseract\$id; Flags: ignoreversion")
    if ($code -ne 'eng') {
        # English stays checked; every other language starts off.
        $fresh.Add("    WizardSelectComponents('!tesseract\$id');")
    }
    $registry.Add("    if RegQueryDWordValue(HKEY_CURRENT_USER, ENGINES_KEY, '$id', V) and (V <> 0) then")
    $registry.Add("      WizardSelectComponents('tesseract\$id')")
    $registry.Add("    else")
    $registry.Add("      WizardSelectComponents('!tesseract\$id');")
    $record.Add("  RegWriteDWordValue(HKEY_CURRENT_USER, ENGINES_KEY, '$id', Ord(WizardIsComponentSelected('tesseract\$id')));")
    $remove.Add("    if not WizardIsComponentSelected('tesseract\$id') then")
    $remove.Add("      DeleteFile(ExpandConstant('{app}\engines\tesseract\tessdata\$code.traineddata'));")
}

$sectionNote = '; Generated by scripts/engine-includes.ps1 from the engine payload. Do not edit.'
$codeNote = '{ Generated by scripts/engine-includes.ps1 from the engine payload. Do not edit. }'

Set-Content -LiteralPath (Join-Path $OutDir 'engine-langs.iss') -Encoding ascii -Value (@(
    $sectionNote
    $components
) -join "`r`n")

Set-Content -LiteralPath (Join-Path $OutDir 'engine-lang-files.iss') -Encoding ascii -Value (@(
    $sectionNote
    $files
) -join "`r`n")

$usesV = if ($languages.Count -gt 0) { "var`r`n  V: Cardinal;`r`n" } else { '' }
$freshBody = if ($fresh.Count -gt 0) { $fresh -join "`r`n" } else { '    { No OCR language data ships with this payload. }' }
$registryBody = if ($registry.Count -gt 0) { $registry -join "`r`n" } else { '    { No OCR language data ships with this payload. }' }
$recordBody = if ($record.Count -gt 0) { $record -join "`r`n" } else { '  { No OCR language data ships with this payload. }' }
$removeBody = if ($remove.Count -gt 0) { $remove -join "`r`n" } else { '    { No OCR language data ships with this payload. }' }

$code = @"
$codeNote
procedure PreselectLanguages(FromRegistry: Boolean);
${usesV}begin
  if not FromRegistry then
  begin
$freshBody
  end
  else
  begin
$registryBody
  end;
end;

procedure RecordLanguageSelection;
begin
$recordBody
end;

procedure RemoveDeselectedLanguages;
begin
$removeBody
end;
"@
Set-Content -LiteralPath (Join-Path $OutDir 'engine-lang-code.iss') -Encoding ascii -Value $code

Write-Host "Engine includes: $($languages.Count) OCR language(s) from $tessdata"
